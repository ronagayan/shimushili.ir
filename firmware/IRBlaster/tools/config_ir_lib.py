#!/usr/bin/env python3
"""Patch the vendored IRremoteESP8266.h so only the listed protocols are compiled.

Usage: python3 config_ir_lib.py ../src/IRremoteESP8266/IRremoteESP8266.h PROTO [PROTO...]
Idempotent: replaces a previous IRBLASTER block if present.
"""
import re
import sys

path, protos = sys.argv[1], sys.argv[2:]
s = open(path).read()
s = re.sub(r"// >>> IRBLASTER CONFIG.*?// <<< IRBLASTER CONFIG\n", "", s, flags=re.S)
block = ["// >>> IRBLASTER CONFIG (generated by tools/config_ir_lib.py)",
         "#define _IR_ENABLE_DEFAULT_ false"]
for p in protos:
    block.append("#define SEND_%s true\n#define DECODE_%s true" % (p, p))
block.append("// <<< IRBLASTER CONFIG\n")
guard = "#define IRREMOTEESP8266_H_\n"
assert guard in s
s = s.replace(guard, guard + "\n".join(block), 1)
open(path, "w").write(s)
print("enabled %d protocols" % len(protos))
