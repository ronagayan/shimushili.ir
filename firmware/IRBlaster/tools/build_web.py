#!/usr/bin/env python3
"""Gzip the files in ../web into ../web_assets.h (served with Content-Encoding: gzip).

Run after editing anything in web/:  python3 tools/build_web.py
"""
import gzip
import os

HERE = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.join(HERE, "..", "web")
OUT = os.path.join(HERE, "..", "web_assets.h")

ASSETS = [  # (file, C name, gzip?)
    ("index.html", "INDEX_HTML", True),
    ("portal.html", "PORTAL_HTML", True),
    ("update.html", "UPDATE_HTML", True),
    ("icon.png", "ICON_PNG", False),
]


def main():
    lines = ["// Generated by tools/build_web.py from web/. Do not edit by hand.", "#pragma once", ""]
    for fn, name, gz in ASSETS:
        data = open(os.path.join(WEB, fn), "rb").read()
        if gz:
            data = gzip.compress(data, compresslevel=9, mtime=0)
        body = ",\n".join(",".join("0x%02x" % c for c in data[i:i + 32]) for i in range(0, len(data), 32))
        lines.append("static const uint8_t %s[] PROGMEM = {\n%s\n};  // %s%s, %d bytes"
                     % (name, body, fn, " (gzip)" if gz else "", len(data)))
        print("%-12s -> %6d bytes" % (fn, len(data)))
    open(OUT, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
